source ../testsupport.sh

# 1. Stage hello's output is staged: its command must not run, but should be printed
#    fully resolved (including late-bound $threads), and world must run for real on the
#    staged data
bpipe run -r -n 2 --staged staged test.groovy test.txt > test.out 2>&1 || err "Pipeline failed with staged outputs"

[ -e doc/index.html ] || err "No HTML report was generated for test"

grep -q "Stage hello using staged outputs from .*staged instead of executing" test.out || err "Failed to find staging message for stage hello"
grep -q "echo REAL hello threads=2 > test.hello.txt" test.out || err "Failed to find fully resolved original command in output"
grep -q "STAGED hello" test.hello.txt || err "Output of hello was not copied from staged file"
grep -q "STAGED hello" test.hello.world.csv || err "Stage world did not run using the staged output of hello"
grep -q "REAL world" test.hello.world.tsv || err "Stage world was not executed"

# 2. Re-running with the same staging leaves everything up to date
bpipe run -n 2 --staged staged test.groovy test.txt > test.out2 2>&1 || err "Re-run with staged outputs failed"
grep -q "using staged outputs" test.out2 && err "Staged outputs were copied again although up to date"
grep -q "pre-existing" test.out2 || err "Expected outputs to be pre-existing on re-run with same staging"

# 3. Running without staging must not reuse the staged dummy data
bpipe run -n 2 test.groovy test.txt > test.out3 2>&1 || err "Run without staging failed"
grep -q "REAL hello" test.hello.txt || err "Staged output was not regenerated by run without staging"
grep -q "REAL hello" test.hello.world.csv || err "Downstream of staged output was not regenerated by run without staging"

# 4. The execute command supports staging too
bpipe execute -n 2 --staged staged -s test.groovy 'hello + world' test.txt > test.out4 2>&1 || err "Execute with staged outputs failed"
grep -q "Stage hello using staged outputs" test.out4 || err "Failed to find staging message for execute"
grep -q "STAGED hello" test.hello.world.csv || err "Execute did not use staged output of hello"

# 5. Layered staging dirs: first wins. world has only one of its two outputs staged,
#    so it must be executed for real, with a warning
bpipe run -n 2 --staged staged_partial,staged test.groovy test.txt > test.out5 2>&1 || err "Run with partial staging failed"
grep -q "STAGED partial hello" test.hello.txt || err "First staging directory did not take precedence"
grep -q "WARNING: stage world has staged files for only some of its outputs" test.out5 || err "No warning for partially staged stage"
grep -q "STAGED partial hello" test.hello.world.csv || err "Partially staged stage world was not executed for real"

# 6. Test mode reports what would be staged without creating anything
rm -rf .bpipe test.hello.*
bpipe test -n 2 --staged staged test.groovy test.txt > test.out6 2>&1
grep -q "outputs would be copied from staged directory" test.out6 || err "Test mode did not report staging"
notexists test.hello.txt

# 7. A missing staging directory is an error
bpipe run --staged does_not_exist test.groovy test.txt > test.out7 2>&1 && err "Expected failure for missing staging directory"
grep -q "does_not_exist does not exist" test.out7 || err "Missing staging directory not reported"

true
